import { chromium } from 'playwright';
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.route((u) => /(^|\.)(mc|mdd)\.yandex\.(ru|net)$/.test(u.hostname), (r) => r.abort());
await ctx.addInitScript(() => { localStorage.setItem('lp.cookieAccepted','true'); localStorage.setItem('lp.region', JSON.stringify({ name: 'Удмуртия', regionId: 'e02392242878498087b248fe5e21e043', sourceDepartmentIds: [] })); });
const p = await ctx.newPage(); let watch = false; const t0 = Date.now();
p.on('request', r => { if (watch && r.url().includes('/api/')) console.log(((Date.now()-t0)/1000).toFixed(1), 'REQ', r.method(), r.url().replace('http://localhost:5190/api/','')); });
p.on('response', r => { if (watch && r.url().includes('/api/')) console.log(((Date.now()-t0)/1000).toFixed(1), 'RES', r.status(), r.url().replace('http://localhost:5190/api/','').slice(0,90)); });
p.on('console', m => console.log('CONSOLE', m.type(), m.text().slice(0,200)));
await p.goto('http://localhost:5190/category/8b23600b-d61b-415f-85b9-952b011d7932', { waitUntil: 'networkidle' });
await p.locator('.pcard').first().getByRole('button', { name: 'В корзину' }).click();
const dlg = p.getByRole('dialog', { name: 'Адрес доставки' });
await dlg.getByLabel('Новый адрес').fill('Ижевск, Пушкинская 154');
await dlg.getByRole('option').first().locator('button').click();
watch = true;
await dlg.getByRole('button', { name: 'Выбрать', exact: true }).click();
await p.waitForTimeout(6000);
console.log('cards', await p.locator('.pcard:not(.pcard--skel)').count());
console.log(await p.evaluate(() => [...window.__lpCache.entries()].map(([k, v]) => k + ' data=' + (v.data !== undefined) + ' promise=' + !!v.promise + ' err=' + (v.error || '')).join('\n')));
await b.close();
